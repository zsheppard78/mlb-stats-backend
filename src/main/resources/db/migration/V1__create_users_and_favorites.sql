-- Accounts and favorite teams.
-- Works for either sign-in style: email + password (password_hash) or Google (google_subject).

CREATE TABLE app_user (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(254) NOT NULL UNIQUE,
    password_hash   VARCHAR(100),             -- bcrypt hash; empty for Google accounts
    google_subject  VARCHAR(64) UNIQUE,       -- Google's account id; empty for email accounts
    display_name    VARCHAR(100),
    theme           VARCHAR(20),              -- the site's color theme, so it follows you between devices
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE favorite_team (
    user_id     BIGINT  NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    team_id     INTEGER NOT NULL,             -- MLB team id, e.g. 158 = Milwaukee Brewers
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, team_id)
);
